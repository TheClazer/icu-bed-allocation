"""Generates db/seed.sql (deterministic). Run: python tools/make_seed.py

The output is plain SQL with one statement per line group, so the app can
re-run it from the "Reset demo data" button.
"""
import random
from pathlib import Path

random.seed(252)

HOSPITALS = [
    (1, "Jayanagar General Hospital", "Jayanagar", 12.929900, 77.582600),
    (2, "Hebbal City Hospital", "Hebbal", 13.035800, 77.597000),
    (3, "Whitefield Care Hospital", "Whitefield", 12.969800, 77.750000),
    (4, "Malleshwaram Medical Centre", "Malleshwaram", 13.003100, 77.564300),
    (5, "Electronic City Hospital", "Electronic City", 12.845200, 77.660200),
    (6, "Indiranagar Critical Care Hospital", "Indiranagar", 12.978400, 77.640800),
    (7, "Koramangala Multispeciality Hospital", "Koramangala", 12.935200, 77.624500),
]

BED_TYPES = [(1, "ICU", 0), (2, "ICU_VENTILATOR", 1), (3, "OXYGEN", 0)]

# Bed n of every hospital: (bed_type_id, ward). bed_id = hospital_id * 100 + n
LAYOUT = {1: (1, "ICU-A"), 2: (1, "ICU-A"), 3: (1, "ICU-A"),
          4: (2, "ICU-V"), 5: (2, "ICU-V"),
          6: (3, "O2-1"), 7: (3, "O2-1"), 8: (3, "O2-1")}

# Exactly ONE free ventilator bed in the whole city (bed 104), so the
# "race for the last bed" demo works straight after a reset.
FREE = {104, 102, 301, 401, 502, 703, 107, 207, 306, 506, 608, 707}
MAINTENANCE = {205, 403}

USERS = [
    (1, None, "Helpline Desk", "108", "HELPLINE"),
    (2, None, "Ambulance KA-01", "9000000001", "AMBULANCE"),
    (3, None, "Ambulance KA-02", "9000000002", "AMBULANCE"),
] + [
    (3 + h, h, f"Ward Staff, {zone}", f"80{h:08d}", "HOSPITAL_STAFF")
    for h, _, zone, _, _ in HOSPITALS
] + [
    (11, None, "Control Room", "100", "CONTROL_ROOM"),
    (12, None, "Suspicious Agent", "9999999999", "HELPLINE"),
]

FIRST_M = ["Ravi", "Arjun", "Suresh", "Rahul", "Vikram", "Manoj", "Prakash", "Nikhil",
           "Kiran", "Ganesh", "Harish", "Ramesh", "Sanjay", "Venkatesh", "Mohan", "Imran",
           "Joseph", "Anil", "Deepak", "Girish", "Naveen"]
FIRST_F = ["Lakshmi", "Meera", "Kavya", "Anitha", "Divya", "Sneha", "Asha", "Deepa",
           "Shalini", "Nandini", "Priya", "Bhavana", "Roopa", "Sunita", "Fatima", "Mary",
           "Geetha", "Rekha", "Usha", "Vani", "Latha"]
LAST = ["Kumar", "Rao", "Reddy", "Gowda", "Sharma", "Iyer", "Nair", "Shetty", "Hegde",
        "Patil", "Khan", "Menon", "Murthy", "Prasad", "Naidu", "Bhat", "Pillai"]

lines = []
out = lines.append


def sql_str(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def ago(hours, plus_min=0):
    expr = f"NOW() - INTERVAL {hours * 60 - plus_min} MINUTE"
    return expr


out("-- City ICU Bed Allocation System")
out("-- seed.sql: simulated demo data (generated by tools/make_seed.py). Safe to re-run.")
out("-- Every name, phone number and patient below is fictional.")
out("")
out("SET @skip_audit = 1;")
out("SET FOREIGN_KEY_CHECKS = 0;")
for t in ["audit_log", "transfer", "reservation", "bed_request", "user_account", "bed", "patient", "bed_type", "hospital"]:
    out(f"TRUNCATE TABLE {t};")
out("SET FOREIGN_KEY_CHECKS = 1;")
out("INSERT INTO sim_clock (id, offset_minutes) VALUES (1, 0) ON DUPLICATE KEY UPDATE offset_minutes = 0;")
out("")

out("INSERT INTO hospital (hospital_id, name, zone, latitude, longitude) VALUES")
out(",\n".join(f"  ({h}, {sql_str(n)}, {sql_str(z)}, {lat:.6f}, {lon:.6f})" for h, n, z, lat, lon in HOSPITALS) + ";")
out("")
out("INSERT INTO bed_type (bed_type_id, name, has_ventilator) VALUES")
out(",\n".join(f"  ({i}, {sql_str(n)}, {v})" for i, n, v in BED_TYPES) + ";")
out("")

# ---- patients and beds -------------------------------------------------------
patients = []  # (patient_id, name, age, gender, phone)


def new_patient(name=None, age=None, gender=None):
    pid = len(patients) + 1
    if name is None:
        gender = random.choice("MF")
        first = random.choice(FIRST_M if gender == "M" else FIRST_F)
        name = f"{first} {random.choice(LAST)}"
        age = random.randint(19, 86)
    phone = f"9{random.randint(100000000, 999999999)}"
    patients.append((pid, name, age, gender, phone))
    return pid


beds = []  # (bed_id, hospital_id, type, ward, status, patient_id)
occupied = []
for h, *_ in HOSPITALS:
    for n, (t, ward) in LAYOUT.items():
        bed_id = h * 100 + n
        if bed_id in FREE:
            beds.append((bed_id, h, t, ward, "FREE", None))
        elif bed_id in MAINTENANCE:
            beds.append((bed_id, h, t, ward, "MAINTENANCE", None))
        else:
            pid = new_patient()
            beds.append((bed_id, h, t, ward, "OCCUPIED", pid))
            occupied.append((bed_id, h, t, pid))

# history-only patients (requests that never turned into an admission here)
fake_names = ["Patient A", "Patient B", "Patient C", "Patient D", "Patient E",
              "Patient F", "Patient G", "Patient H", "Patient I"]
suspicious_patients = [new_patient(n, None, None) for n in fake_names]
honest_extra = [new_patient() for _ in range(3)]

out("INSERT INTO patient (patient_id, name, age, gender, contact_phone) VALUES")
out(",\n".join(f"  ({p}, {sql_str(n)}, {sql_str(a)}, {sql_str(g)}, {sql_str(ph)})" for p, n, a, g, ph in patients) + ";")
out("")
out("INSERT INTO bed (bed_id, hospital_id, bed_type_id, ward, status, patient_id) VALUES")
out(",\n".join(f"  ({b}, {h}, {t}, {sql_str(w)}, {sql_str(s)}, {sql_str(p)})" for b, h, t, w, s, p in beds) + ";")
out("")
out("INSERT INTO user_account (user_id, hospital_id, name, phone, role) VALUES")
out(",\n".join(f"  ({u}, {sql_str(h)}, {sql_str(n)}, {sql_str(ph)}, {sql_str(r)})" for u, h, n, ph, r in USERS) + ";")
out("")

# ---- request and reservation history ----------------------------------------
hosp_coord = {h: (lat, lon) for h, _, _, lat, lon in HOSPITALS}
requests = []      # (request_id, patient_id, raised_by, type, severity, lat, lon, raw, status, created_expr)
reservations = []  # (request_id, bed_id, status, expires_expr, admitted_expr, created_expr)


def jitter(v):
    return round(v + random.uniform(-0.02, 0.02), 6)


raisers = [1, 2, 3]
for i, (bed_id, h, t, pid) in enumerate(occupied):
    hours = random.randint(3, 120)
    lat, lon = hosp_coord[h]
    rid = len(requests) + 1
    created = ago(hours)
    requests.append((rid, pid, raisers[i % 3], t, random.randint(3, 5), jitter(lat), jitter(lon), None, "FULFILLED", created))
    reservations.append((rid, bed_id, "ADMITTED", ago(hours, 30), ago(hours, random.randint(8, 25)), created))

all_beds_of_type = {t: [b for b, _, bt, *_ in beds if bt == t] for t, *_ in BED_TYPES}

# Suspicious Agent: 9 holds, 1 admitted, 8 never converted (bed blocking pattern)
for j, pid in enumerate(suspicious_patients):
    t = random.choice([1, 3])
    bed_id = random.choice(all_beds_of_type[t])
    h = bed_id // 100
    lat, lon = hosp_coord[h]
    hours = 24 * random.randint(1, 6) + random.randint(0, 20)
    rid = len(requests) + 1
    created = ago(hours)
    if j == 0:
        requests.append((rid, pid, 12, t, 5, jitter(lat), jitter(lon), "urgent bed needed", "FULFILLED", created))
        reservations.append((rid, bed_id, "ADMITTED", ago(hours, 30), ago(hours, 20), created))
    else:
        status = "CANCELLED" if j == 4 else "EXPIRED"
        requests.append((rid, pid, 12, t, 5, jitter(lat), jitter(lon), "urgent bed needed", "CANCELLED", created))
        reservations.append((rid, bed_id, status, ago(hours, 30), None, created))

# Honest accounts miss a few too: two expired for Helpline, one cancelled by KA-02
for (pid, user, status) in zip(honest_extra, [1, 1, 3], ["EXPIRED", "EXPIRED", "CANCELLED"]):
    t = random.choice([1, 2, 3])
    bed_id = random.choice(all_beds_of_type[t])
    lat, lon = hosp_coord[bed_id // 100]
    hours = random.randint(30, 140)
    rid = len(requests) + 1
    created = ago(hours)
    requests.append((rid, pid, user, t, random.randint(2, 4), jitter(lat), jitter(lon), None, "CANCELLED", created))
    reservations.append((rid, bed_id, status, ago(hours, 30), None, created))

out("INSERT INTO bed_request (request_id, patient_id, raised_by, bed_type_id, severity, pickup_lat, pickup_lon, raw_text, status, created_at) VALUES")
out(",\n".join(
    f"  ({r}, {p}, {u}, {t}, {s}, {lat:.6f}, {lon:.6f}, {sql_str(raw)}, {sql_str(st)}, {c})"
    for r, p, u, t, s, lat, lon, raw, st, c in requests) + ";")
out("")

# Reservations in chronological order so ids grow with time
reservations.sort(key=lambda x: -int(x[5].split("INTERVAL ")[1].split(" ")[0]))
out("INSERT INTO reservation (request_id, bed_id, status, hold_expires_at, admitted_at, created_at) VALUES")
out(",\n".join(
    f"  ({r}, {b}, {sql_str(st)}, {e}, {a if a else 'NULL'}, {c})"
    for r, b, st, e, a, c in reservations) + ";")
out("")
out("SET @skip_audit = NULL;")
out("INSERT INTO audit_log (user_id, action, entity_name, entity_id, details) VALUES (NULL, 'DEMO_DATA_LOADED', 'system', NULL, JSON_OBJECT('source', 'seed.sql'));")

path = Path(__file__).resolve().parent.parent / "db" / "seed.sql"
path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"wrote {path} ({len(patients)} patients, {len(beds)} beds, {len(requests)} requests)")
